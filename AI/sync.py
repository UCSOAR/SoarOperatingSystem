#!/usr/bin/env python3
"""
Generate SOAR AI agent files in a board repository from SoarOS/AI.

Run from the board repo (the one that includes SoarOS as a submodule):

    python3 SoarOS/AI/sync.py            # write / update the generated files
    python3 SoarOS/AI/sync.py --check    # CI: exit 1 if generated files are out of date

Generated files (overwritten on every sync, do not edit them by hand):

    AGENTS.md             SoarOS/AI/AGENTS.md + BOARD.md   Codex, Gemini, Claude (via CLAUDE.md)
    CLAUDE.md             imports AGENTS.md                Claude Code
    GEMINI.md             imports AGENTS.md                Gemini CLI
    .claude/skills/<n>/   copy of SoarOS/AI/skills/<n>/    Claude Code
    .agents/skills/<n>/   copy of SoarOS/AI/skills/<n>/    Codex

Only skill folders that contain a SKILL.md are synced. Skills the board added itself
(folders without the generated marker file) are never touched.

Uses only the Python standard library and works on Windows, macOS and Linux.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path
from typing import Dict, List

AI_DIR = Path(__file__).resolve().parent
SOAROS_DIR = AI_DIR.parent
SKILLS_SRC_DIR = AI_DIR / "skills"

GENERATED_MARKER = "GENERATED by SoarOS AI sync"  # Identifies files this script owns
SKILL_MARKER_FILE = ".soar-ai-generated"  # Placed in every skill folder this script owns
SKILL_DEST_DIRS = (Path(".claude") / "skills", Path(".agents") / "skills")
IGNORED_NAMES = {".DS_Store", "Thumbs.db", "__pycache__"}  # Never copied into skills
CODEX_MAX_BYTES = 32 * 1024  # Codex's default project_doc_max_bytes

EXIT_OK = 0
EXIT_STALE = 1
EXIT_ERROR = 2


class SyncError(Exception):
    pass


def normalize(data: bytes) -> bytes:
    """Convert CRLF to LF for text files so Windows checkouts compare equal. Binary data is unchanged."""
    try:
        data.decode("utf-8")
    except UnicodeDecodeError:
        return data
    return data.replace(b"\r\n", b"\n")


def read_text(path: Path) -> str:
    return normalize(path.read_bytes()).decode("utf-8")


def finish(text: str) -> bytes:
    """Strip trailing whitespace and end with exactly one newline (matches the pre-commit hooks)."""
    lines = [line.rstrip() for line in text.split("\n")]
    return ("\n".join(lines).strip("\n") + "\n").encode("utf-8")


def find_board_root(override: str | None) -> Path:
    board_root = Path(override).resolve() if override else SOAROS_DIR.parent

    try:
        soaros_rel = SOAROS_DIR.relative_to(board_root).as_posix()
    except ValueError:
        raise SyncError(f"{SOAROS_DIR} is not inside the board repo {board_root}.")

    gitmodules = board_root / ".gitmodules"
    pattern = rf"^\s*path\s*=\s*{re.escape(soaros_rel)}\s*$"
    if not gitmodules.is_file() or not re.search(pattern, read_text(gitmodules), re.MULTILINE):
        raise SyncError(
            f"{board_root} does not look like a board repo: no .gitmodules entry for '{soaros_rel}'.\n"
            "Run this from a board repo that includes SoarOS as a submodule, or pass --board-root."
        )
    return board_root


def header(soaros_rel: str, lines: List[str]) -> str:
    body = "\n".join(lines)
    return (
        f"<!--\n{GENERATED_MARKER}. Do not edit this file by hand.\n{body}\n"
        f"Regenerate:   python3 {soaros_rel}/AI/sync.py\n-->\n"
    )


def build_outputs(board_root: Path) -> Dict[Path, bytes]:
    """Return every generated file as {path relative to board root: content}."""
    soaros_rel = SOAROS_DIR.relative_to(board_root).as_posix()
    outputs: Dict[Path, bytes] = {}

    # AGENTS.md = shared rules + board notes
    shared = read_text(AI_DIR / "AGENTS.md").strip()
    board_md = board_root / "BOARD.md"
    agents = header(
        soaros_rel,
        [
            f"Shared rules: {soaros_rel}/AI/AGENTS.md (edit in the SoarOS repo)",
            "Board notes:  BOARD.md (edit in this repo)",
        ],
    )
    agents += "\n" + shared + "\n"
    if board_md.is_file():
        agents += "\n---\n\n" + read_text(board_md).strip() + "\n"
    outputs[Path("AGENTS.md")] = finish(agents)

    # CLAUDE.md / GEMINI.md just import AGENTS.md so all tools share one set of rules
    for name in ("CLAUDE.md", "GEMINI.md"):
        content = header(soaros_rel, ["All instructions live in AGENTS.md."]) + "\n@AGENTS.md\n"
        outputs[Path(name)] = finish(content)

    # Skills, copied into each tool's skill folder
    for skill in sorted(SKILLS_SRC_DIR.iterdir()) if SKILLS_SRC_DIR.is_dir() else []:
        if not (skill / "SKILL.md").is_file():
            continue  # Placeholder or unfinished skill
        for src in sorted(skill.rglob("*")):
            if not src.is_file() or any(part in IGNORED_NAMES for part in src.relative_to(skill).parts):
                continue
            data = normalize(src.read_bytes())
            for dest_dir in SKILL_DEST_DIRS:
                outputs[dest_dir / skill.name / src.relative_to(skill)] = data
        for dest_dir in SKILL_DEST_DIRS:
            outputs[dest_dir / skill.name / SKILL_MARKER_FILE] = finish(
                f"{GENERATED_MARKER}: this folder is a copy of {soaros_rel}/AI/skills/{skill.name}/"
            )

    return outputs


def find_conflicts(board_root: Path, outputs: Dict[Path, bytes]) -> List[Path]:
    """Files or skill folders the board owns that a sync would overwrite."""
    conflicts = []
    for name in ("AGENTS.md", "CLAUDE.md", "GEMINI.md"):
        path = board_root / name
        if path.is_file() and GENERATED_MARKER not in read_text(path):
            conflicts.append(Path(name))

    skill_dirs = {Path(*rel.parts[:3]) for rel in outputs if len(rel.parts) > 3}  # e.g. .claude/skills/<name>
    for rel_dir in sorted(skill_dirs):
        path = board_root / rel_dir
        if path.is_dir() and not (path / SKILL_MARKER_FILE).is_file():
            conflicts.append(rel_dir)
    return conflicts


def find_stale(board_root: Path, outputs: Dict[Path, bytes]) -> List[Path]:
    """Files inside generated skill folders that are no longer produced (skill or file removed upstream)."""
    stale = []
    for dest_dir in SKILL_DEST_DIRS:
        root = board_root / dest_dir
        if not root.is_dir():
            continue
        for skill_dir in sorted(root.iterdir()):
            if not (skill_dir / SKILL_MARKER_FILE).is_file():
                continue  # Board-owned skill
            for path in sorted(skill_dir.rglob("*")):
                rel = path.relative_to(board_root)
                if path.is_file() and rel not in outputs:
                    stale.append(rel)
    return stale


def remove_empty_dirs(board_root: Path) -> None:
    for dest_dir in SKILL_DEST_DIRS:
        root = board_root / dest_dir
        if not root.is_dir():
            continue
        for path in sorted(root.rglob("*"), key=lambda p: len(p.parts), reverse=True):
            if path.is_dir() and not any(path.iterdir()):
                path.rmdir()


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate SOAR AI agent files in a board repo from SoarOS/AI.")
    parser.add_argument("--check", action="store_true", help="don't write anything; exit 1 if files are out of date")
    parser.add_argument("--force", action="store_true", help="overwrite hand-written AGENTS.md/CLAUDE.md/GEMINI.md")
    parser.add_argument("--board-root", help="board repo root (default: the folder containing SoarOS)")
    args = parser.parse_args()

    try:
        board_root = find_board_root(args.board_root)
    except SyncError as err:
        print(f"error: {err}", file=sys.stderr)
        return EXIT_ERROR

    outputs = build_outputs(board_root)
    soaros_rel = SOAROS_DIR.relative_to(board_root).as_posix()

    if not (board_root / "BOARD.md").is_file():
        print(
            f"warning: no BOARD.md. Copy {soaros_rel}/AI/BOARD.template.md to BOARD.md and fill it in.",
            file=sys.stderr,
        )
    agents_size = len(outputs[Path("AGENTS.md")])
    if agents_size > CODEX_MAX_BYTES:
        print(
            f"warning: AGENTS.md is {agents_size} bytes; Codex only reads the first {CODEX_MAX_BYTES}.",
            file=sys.stderr,
        )

    conflicts = find_conflicts(board_root, outputs)
    if conflicts and not args.force:
        print("error: these exist but were not generated by this script, refusing to overwrite:", file=sys.stderr)
        for rel in conflicts:
            print(f"  {rel.as_posix()}", file=sys.stderr)
        print("Move their content into BOARD.md (or rename the skill), or rerun with --force.", file=sys.stderr)
        return EXIT_ERROR

    changed = [
        rel
        for rel, data in sorted(outputs.items())
        if not (board_root / rel).is_file() or normalize((board_root / rel).read_bytes()) != data
    ]
    stale = find_stale(board_root, outputs)

    if args.check:
        if not changed and not stale:
            print("SOAR AI files are up to date.")
            return EXIT_OK
        print("SOAR AI files are out of date:", file=sys.stderr)
        for rel in changed:
            print(f"  outdated: {rel.as_posix()}", file=sys.stderr)
        for rel in stale:
            print(f"  stale:    {rel.as_posix()}", file=sys.stderr)
        print(f"Fix: run 'python3 {soaros_rel}/AI/sync.py' and commit the result.", file=sys.stderr)
        return EXIT_STALE

    for rel in changed:
        path = board_root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(outputs[rel])
        print(f"updated: {rel.as_posix()}")
    for rel in stale:
        (board_root / rel).unlink()
        print(f"removed: {rel.as_posix()}")
    remove_empty_dirs(board_root)

    if not changed and not stale:
        print("SOAR AI files are up to date.")
    return EXIT_OK


if __name__ == "__main__":
    sys.exit(main())
